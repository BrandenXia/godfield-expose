"""Bundle the extension's shared sources into a self-contained userscript."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'userscript' / 'godfield-room-inspector.user.js'
REPOSITORY = 'https://github.com/BrandenXia/godfield-expose'
DOWNLOAD = 'https://raw.githubusercontent.com/BrandenXia/godfield-expose/main/userscript/godfield-room-inspector.user.js'


def build():
    extension = ROOT / 'extension'
    manifest = json.loads((extension / 'manifest.json').read_text(encoding='utf-8'))
    version = manifest['version']
    if json.loads((ROOT / 'package.json').read_text(encoding='utf-8'))['version'] != version:
        raise SystemExit('package.json and manifest.json versions must match')

    sources = []
    for entry in manifest['content_scripts']:
        if entry['matches'] != ['https://godfield.net/*'] or entry['run_at'] != 'document_start':
            raise SystemExit('Review userscript metadata after changing extension scope or timing')
        for name in entry['js']:
            source = extension / name
            if not source.is_file() or not source.resolve().is_relative_to(extension.resolve()):
                raise SystemExit(f'Invalid extension resource: {name}')
            sources.append(f'// Source: extension/{name}\n{source.read_text(encoding="utf-8").rstrip()}\n')

    metadata = f'''// ==UserScript==
// @name         God Field Room Inspector
// @namespace    {REPOSITORY}
// @version      {version}
// @description  {manifest['description']}
// @homepageURL  {REPOSITORY}
// @supportURL   {REPOSITORY}/issues
// @updateURL    {DOWNLOAD}
// @downloadURL  {DOWNLOAD}
// @match        https://godfield.net/*
// @run-at       document-start
// @sandbox      raw
// @grant        none
// @noframes
// ==/UserScript==

// Generated by scripts/build-userscript.py. Edit extension/ sources, then rebuild.
// Item data and translations originate from God Field. See THIRD_PARTY_NOTICES.md.
(() => {{
  'use strict';
  // Keep CommonJS detection in shared sources independent of page globals.
  const module = undefined;
'''
    return metadata + '\n' + '\n'.join(sources) + '\n})();\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if the committed userscript is stale')
    args = parser.parse_args()
    content = build()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding='utf-8') != content:
            raise SystemExit('Userscript is out of date. Run npm run build:userscript.')
        print('Userscript matches shared extension sources.')
    else:
        OUTPUT.parent.mkdir(exist_ok=True)
        OUTPUT.write_text(content, encoding='utf-8')
        print(OUTPUT)


if __name__ == '__main__':
    main()
